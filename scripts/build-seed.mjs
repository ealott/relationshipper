// Builds the question-bank migrations from the research bank in shared/questions: the original
// bank goes in 0002_seed_questions.sql, and questions written later go in the migration named by
// their `addedIn`, since a migration runs only once per database. Run: npm run seed
import { writeFileSync } from 'node:fs';
import { build } from 'esbuild';

const bundle = await build({
  entryPoints: [new URL('../shared/questions/index.ts', import.meta.url).pathname],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
});
const { SEED_QUESTIONS } = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`);

// A fixed timestamp keeps the generated file stable between runs.
const SEEDED_AT = Date.UTC(2026, 9, 11);
const sql = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`);

const ORIGINAL = '0002_seed_questions';
const batches = Map.groupBy(SEED_QUESTIONS, (q) => q.addedIn ?? ORIGINAL);

for (const [migration, questions] of batches) {
  const chunks = [];
  for (let i = 0; i < questions.length; i += 40) {
    const rows = questions.slice(i, i + 40).map((q) =>
      `  (${[q.id, q.category, q.text, q.depth, q.audience ?? null, 'research', 'active', SEEDED_AT, SEEDED_AT].map(sql).join(', ')})`,
    );
    chunks.push(
      `INSERT INTO questions (id, category, text, depth, audience, source, status, created_at, updated_at) VALUES\n${rows.join(',\n')}\nON CONFLICT (id) DO NOTHING;`,
    );
  }
  const out = new URL(`../migrations/${migration}.sql`, import.meta.url);
  writeFileSync(
    out,
    `-- Generated by scripts/build-seed.mjs from shared/questions — do not edit by hand.\n-- ${questions.length} research-based prompts.\n\n${chunks.join('\n\n')}\n`,
  );
  console.log(`Wrote ${questions.length} questions to ${out.pathname}`);
}
